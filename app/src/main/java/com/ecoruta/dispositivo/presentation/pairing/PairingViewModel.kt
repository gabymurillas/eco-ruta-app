package com.ecoruta.dispositivo.presentation.pairing

import androidx.annotation.StringRes
import androidx.lifecycle.ViewModel
import androidx.lifecycle.viewModelScope
import com.ecoruta.dispositivo.core.onFailure
import com.ecoruta.dispositivo.domain.usecase.PairDeviceUseCase
import com.ecoruta.dispositivo.domain.usecase.WasPairedBeforeUseCase
import com.ecoruta.dispositivo.presentation.common.toMessageRes
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.flow.update
import kotlinx.coroutines.launch

/** Everything the pairing screen shows. */
data class PairingUiState(
    val code: String = "",
    val isLoading: Boolean = false,
    /** The pairing ended (session revoked): the screen explains why it asks for a code again. */
    val sessionEnded: Boolean = false,
    @StringRes val errorRes: Int? = null,
) {
    val canSubmit: Boolean get() = code.length == PAIRING_CODE_LENGTH && !isLoading
}

/** Codes generated by the admin panel (`ecoruta-web/src/domain/vinculacion.ts`) are this long. */
const val PAIRING_CODE_LENGTH = 5

/** Collects the code and pairs. On success the persisted session changes and the screen follows. */
class PairingViewModel(
    private val pairDevice: PairDeviceUseCase,
    wasPairedBefore: WasPairedBeforeUseCase,
) : ViewModel() {

    private val _uiState = MutableStateFlow(PairingUiState())
    val uiState: StateFlow<PairingUiState> = _uiState.asStateFlow()

    init {
        viewModelScope.launch {
            val ended = wasPairedBefore()
            _uiState.update { it.copy(sessionEnded = ended) }
        }
    }

    /** Keeps only letters and digits, upper-cased, up to the code length: what the panel shows. */
    fun onCodeChange(input: String) {
        val code = input.uppercase().filter { it in 'A'..'Z' || it in '0'..'9' }.take(PAIRING_CODE_LENGTH)
        _uiState.update { it.copy(code = code, errorRes = null) }
    }

    fun onSubmit() {
        val current = _uiState.value
        if (!current.canSubmit) return

        _uiState.update { it.copy(isLoading = true, errorRes = null) }
        viewModelScope.launch {
            // On success the persisted session changes and navigation moves on by itself.
            pairDevice(current.code).onFailure { error ->
                _uiState.update { it.copy(errorRes = error.toMessageRes()) }
            }
            _uiState.update { it.copy(isLoading = false) }
        }
    }
}
